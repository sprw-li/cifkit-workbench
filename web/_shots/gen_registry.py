# -*- coding: utf-8 -*-
"""Generate web/assets/cif-registry.js from cifkit's own export registry.

Offline fallback for the frontend: when GET /api/bootstrap is unreachable the
export scenario still needs the format / bundle list. It must come from cifkit
itself (CONTRACT.md section 3.1: formats/bundles must come from cifkit), so this
script dumps cifkit.export.FORMAT_INFO / BUNDLE_INFO verbatim -- nothing is
hand-written.

Usage: .venv/Scripts/python.exe web/_shots/gen_registry.py
"""
import json
import os
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
WEB = HERE.parent
WORKBENCH = WEB.parent             # 本仓库根


def _cifkit_root() -> pathlib.Path:
    """cifkit 检出根：CIFKIT_ROOT → 同级/同仓检出 → 已安装包所在根。"""
    candidates = []
    env_root = os.environ.get("CIFKIT_ROOT")
    if env_root:
        candidates.append(pathlib.Path(env_root))
    candidates += [WORKBENCH.parent / "Project5-skill-cif", WORKBENCH.parent]
    for cand in candidates:
        if (cand / "cifkit" / "__init__.py").is_file():
            return cand.resolve()
    try:
        import cifkit  # noqa: PLC0415

        root = pathlib.Path(cifkit.__file__).resolve().parents[1]
        if (root / "cifkit" / "__init__.py").is_file():
            return root
    except Exception:  # noqa: BLE001 - 未安装
        pass
    return WORKBENCH.parent


sys.path.insert(0, str(_cifkit_root()))

from cifkit.export import BUNDLE_INFO, FORMAT_INFO  # noqa: E402

OUT = pathlib.Path(__file__).resolve().parents[1] / "assets" / "cif-registry.js"
HEADER = (
    "/* AUTO-GENERATED by _shots/gen_registry.py from the cifkit.export registry." + chr(10)
    + "   Do not edit by hand; re-run the script after upgrading cifkit. */" + chr(10)
)


def main() -> int:
    payload = {
        "source": "cifkit.export.FORMAT_INFO / BUNDLE_INFO (generated)",
        "formats": FORMAT_INFO,
        "bundles": {k: v.get("description", "") for k, v in BUNDLE_INFO.items()},
        "bundle_missing": {k: v.get("missing", []) for k, v in BUNDLE_INFO.items()},
    }
    body = json.dumps(payload, ensure_ascii=False, indent=2)
    OUT.write_text(HEADER + "window.CIF_REGISTRY = " + body + ";" + chr(10), encoding="utf-8")
    print("wrote", OUT)
    print("formats", len(payload["formats"]), "bundles", len(payload["bundles"]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
